# Preferences — 用户自己的喜好/习惯/标准
# ═══════════════════════════════════════════════════════════

PREFERENCES_EXTRACT_PROMPT = """从用户发言中提取【用户自己】的喜好、习惯、厌恶或个人标准。

## 识别特征（任一即可）
- 第一人称直接陈述个人态度：喜好、厌恶、在意的维度、个人要求
- 自述行为模式：频率（一般/总是/从不）、条件性（"如果…我就…"）、时间性（早/晚/周末）
- 口语化暗示：感受词（受不了/头疼/看不下去）或反问式

## 不属于（关键 — 整句就不应提取）
当句子**没有明显的"描述我这个人"的视角**时，整路返回空：
- 句子整体是对 Agent 的规则式指令（"报告要…"、"以后…"、"跟 <实体> 沟通要…"、"不要 XX"） → 整路空，该句归 agent_rules
- **命令 Agent 输出/行为，即使包含"每次/我"等字眼**（"每次给我建议的时候列出 X"、"算了还是用 X 吧"、"重要客户的分析要单独出报告"）→ 整路空，该句归 agent_rules
  - 判别：动作执行者是 Agent（"给我 X"、"输出 X"、"回复 X"），而不是在描述"我这个人的喜好"
- 更新/撤销规则（"算了不用 X 了"、"改成 Y 吧"、"取消之前的 X"）→ 整路空，该句归 agent_rules
- 句子是对第三方事实的陈述 → 整路空，该句归 entities
- 句子是身份/组织描述 → 整路空，该句归 profile
- 句子是单次操作 → 整路空

## 核心边界（易混淆处）
| 句式                        | 归属          | 依据                  |
|----------------------------|---------------|----------------------|
| "我要求 X"                   | preferences   | 表达个人标准          |
| "X 统一为 Y"（无主语/规则式）   | agent_rules   | 持久性输出约束        |
| "我一般不加班"                | preferences   | 个人习惯              |
| "我们部门不加班"              | profile       | 组织文化              |
| "<角色>喜欢 X"（第三方主语）    | entities      | 描述第三方            |

其他不属于的情况：命令 Agent（无主观感受词的规则式） / 身份 / 单次操作 / 寒暄。

## 粒度
- 按语义维度分条（reply_format、data_display、work_habit、communication 等 slug）
- 同一维度仅保留一条（最新状态）

## 用户发言
{user_messages}

## 输出
```json
{{"preferences": [{{"slug": "<英文下划线>", "abstract": "<1 句>", "overview": "<Markdown>", "content": "<完整叙述>"}}]}}
```
无偏好返回 `{{"preferences": []}}`。
""" + _COMMON_OUTPUT_RULES


