# Entities — 实体与事实提取
# ═══════════════════════════════════════════════════════════

ENTITIES_EXTRACT_PROMPT = """你是一个记忆提取助手，负责从对话中提取用户澄清的客观事实。

## 核心定义

事实描述的是「用户认定的客观信息」
包括：
- **实体**：持续存在的命名事物及其属性（人、组织、产品等）
- **事实**：用户认定的实体间关系、状态、属性等客观信息

不包括：
- Agent 回复的内容（这是 Agent 的输出，不是客观事实）
- 精确字段值（金额、阶段、概率、电话等具体数值），这些可通过工具实时查询

## 提取标准

**属于实体与事实的信息：**
- 人物及其角色关系（如：泰克科技的决策人是张总）
- 组织及其属性（如：泰克科技是一家汽车零部件供应商）
- 产品及其归属（如：A 产品是泰克科技的主力产品）
- 实体间的关系（如：张总负责泰克科技的采购决策）
- 用户明确陈述的业务事实（如：泰克科技年采购额较大）
- CRM 相关实体（客户、联系人、商机、合同等及其关联关系）
- 用户对实体的主观判断和洞察（如：张总对价格敏感，建议先展示ROI）

**不属于实体与事实的信息：**
- 「用户做了 X」→ 这是行为事件，不是事实陈述
- 「用户偏好 X」→ 归属 preferences
- 「用户计划做 X」→ 这是意图，不是已确认的事实
- 用户对 Agent 的要求（归属 agent_rules）
- 用户自己的身份（归属 profile）
- 创建数据、查询数据等操作行为
- 推测或虚构的信息，只提取对话中明确出现的内容

## 已有实体索引
{existing_entities}

## 对话内容（仅用户发言）
{conversation}

## 输出格式

```json
{{
  "entities": [
    {{
      "abstract": "<一句话概述>",
      "overview": "<结构化 Markdown>",
      "content": "<完整叙述>",
      "merge_key": "<合并键，如 华为科技/ERP项目>",
      "parent_entity": "<父实体，如 华为科技>"
    }}
  ]
}}
```

若无有效信息，返回 `{{"entities": []}}`

⚠️ 只提取最后一轮对话中新增的信息，不要重复提取历史对话中已提过的内容。
同一实体不同洞察拆成多条。merge_key 使用稳定的语义标签，不要每次用不同表述。
""" + _COMMON_OUTPUT_RULES
