# Agent Rules — 对 Agent 未来行为的持久约束
# ═══════════════════════════════════════════════════════════

AGENT_RULES_EXTRACT_PROMPT = """从用户发言中提取【对 Agent 未来行为的持久约束】，合并到已有规则后输出完整版本。

## 识别原则
两个条件同时满足：
1. **行为指向**：约束 Agent 的输出、沟通、流程、角色或禁止事项
2. **持久性**：规则可复用到未来同类场景，不是"这次/刚才"的单次调整

允许省略主语。判定动作执行者是否为 Agent 的标志：
- 主句主语或隐含主语是 Agent / 报告 / 回复 / 邮件 / 分析 / 输出等 Agent 产物
- 规则对"未来每一次同类场景"都有效，而非描述一次性个人动作

判别：**该规则在下一次类似请求中 Agent 是否应继续遵守**。

## 不属于（整句归他路，本路返空）
- 句子整体是在**描述用户本人**（个人习惯、性格、喜好、厌恶）→ preferences 的事
  - 标志：主语是"我"、谓语是个人态度或行为（喜欢、在意、一般、每次、受不了 等同类表达）
  - 例：「我一般不加班」、「我喜欢简洁风格」、「看报表我更关注同比」
- 纯身份或组织描述 → profile
- 对第三方事实的纯陈述（动作未指向 Agent）→ entities
- 单次调整、评价、感叹 → 不提取
  - 如「算了还是用 X 吧」（无泛化对象）、「这次 X 一下」、「感觉你像 X」

## 多维度混合处理
句子同时含个人态度和 Agent 规则时，两路独立提取：
- "我喜欢简洁，你回复不超过 3 句"：本路取"回复不超过 3 句"
- 核心判别：句中是否存在**泛化的 Agent 行为约束**（格式、长度、频率、渠道、流程）

## 真歧义处理
省略主语的条件句可能有多种合理解读。按文本最直接的证据判断；证据不足时可单侧提取。

## 核心边界
| 句式                         | 归属          |
|------------------------------|---------------|
| "以后分析要深入一些"            | agent_rules（持久反馈式规则）|
| "这次分析深入一些"              | 不提取（单次）              |
| "跟 <实体> 沟通要用正式语气"     | agent_rules（命令 Agent）   |
| "<实体> 那边要求正式语气"        | entities（陈述事实）         |
| "你就像我的私人助理一样"          | agent_rules（定义角色）      |
| "感觉你像私人助理"               | 不提取（评价）                |
| "我喜欢 X"（无 Agent 行为约束）   | preferences 的事（本路空）    |

## 已有规则
{existing_rules}

## 用户发言
{user_messages}

## 输出
- 有新指令：`{{"agent_rules": {{"content": "<合并后完整规则>"}}}}`
- 无新指令：`{{"agent_rules": {{}}}}`
""" + _COMMON_OUTPUT_RULES


