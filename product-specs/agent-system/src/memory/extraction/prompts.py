"""四路并行提取提示词

设计原则：
1. 用"语义原则"代替"关键词枚举"，避免对具体动词/句式过拟合
2. 具名业务实体（华为/腾讯/张总/飞书 …）全部替换为通用占位符（<角色>/<实体>/<工具>）
3. 每路只规定语义识别标准与跨维度边界，不试图穷举所有反例
4. 输出规则统一在文件顶部定义
5. 明确承认真歧义的存在：允许 LLM 在主语省略的条件句等真歧义场景单标或双标，不强求

大小目标：每个提示词 ≤ 1500 chars。
"""

