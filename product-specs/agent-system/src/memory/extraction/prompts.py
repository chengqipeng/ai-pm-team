# Agent Rules — 对 Agent 未来行为的持久约束
# ═══════════════════════════════════════════════════════════

AGENT_RULES_EXTRACT_PROMPT = """从用户发言中提取【对 Agent 未来行为的持久约束】，合并到已有规则后输出完整版本。

## 两个必要条件（同时满足）
1. 指向 Agent 的未来行为：角色 / 输出 / 沟通 / 流程 / 禁止
2. 具持久性：显式标志（以后/每次/默认/统一/所有）或语义上是泛化规则（非"这次/刚才"）

允许省略主语——"报告要含 X"、"回复不超过 N 字" 等规则式即使无"你"字也属本维度。

## 识别要点补充
- **更新/撤销式指令**同样属 agent_rules：
  - "取消之前 X 限制"、"改成 Y 吧"（上下文显示是调整 Agent 既有规则）
  - 判别：只有"算了还是用 Y 吧"这种**无泛化对象**的单次切换不算（单次调整）
- **即使主句是偏好/习惯，只要句中包含对 Agent 未来行为的持久约束，就应提取 agent_rules**：
  - 「如果急的微信说，不急的发邮件」→ 沟通渠道的持久规则（主语虽省略但动作执行者是 Agent）
  - 「别给我发那种长报告，一页纸搞定最好」→ 报告长度的持久约束
  - 「早上 9 点前别给我推消息」→ 时间窗禁止规则
  - 「能用图就别用表」→ 输出形式的泛化规则
  - 「我要求金额用万为单位」→ 数值格式的持久规则（"我要求"等价于命令）
  - 判别：这些都是泛化到"所有同类场景都适用"，不是单次调整

## 不属于（关键 — 整句就不应提取）
仅当句子**没有任何持久性对 Agent 的约束**时才整路返空：
- 纯个人性格/感受陈述无行为指令（"我这个人不喜欢绕弯子" 无后续指令部分 → 归 preferences）
- 纯身份描述（"我是…"、"我们…"）→ 整路空，该句归 profile
- 单次操作（"这次…"、"帮我…"、"算了还是用 X 吧"这种**无泛化对象**的一次性调整）→ 整路空
- 评价/感叹（"感觉你像私人助理"）→ 整路空
- 对第三方事实的纯陈述（主语是第三方，动作未指向 Agent）→ 归 entities

## 混合句处理（非常重要）
若句中**既有偏好/感受表达，又有持久性规则**，本路仍要提取规则部分：
- "我喜欢简洁风格，**你回复不要超过 3 句话**" → 规则："回复不超过 3 句话"
- "别给我发那种长报告，**一页纸搞定最好**" → 规则："报告一页纸以内"
- "我要求金额用万为单位" → 规则："金额用万为单位"（"我要求"等价命令）
- 判别：**看是否存在可泛化到未来同类场景的约束**（输出格式、时间窗、沟通渠道、长度等）

## 纯偏好表达不提取（关键）
若句子仅陈述个人喜好且**未明示 Agent 应采取对应行动**，本路返空：
- "我喜欢用 <工具> 沟通" → 仅表达个人习惯，没有说"你以后也用 <工具>"→ 本路空
- "我喜欢看 PPT" → 个人偏好，没有要求 Agent 输出 PPT → 本路空
- "我这个人不喜欢绕弯子"（后无对 Agent 的具体指令）→ 本路空
- 判别：**只有当句子包含对 Agent 输出/行为的具体约束时才提取**。"我喜欢 X" 本身只是偏好事实，除非紧跟"你 Y" 或蕴含泛化规则（如"报告要/回复不超过/金额统一"等句式）

## 核心边界（易混淆处）
| 句式                         | 归属          |
|------------------------------|---------------|
| "以后分析要深入一些"            | agent_rules   |
| "这次分析深入一些"              | 不提取（单次）|
| "跟 <实体> 沟通要用正式语气"     | agent_rules（命令 Agent）|
| "<实体> 那边要求正式语气"        | entities（陈述事实）     |
| "你就像我的私人助理一样"          | agent_rules（定义角色）  |
| "感觉你像私人助理"               | 不提取（评价）           |

其他不属于：描述"我这个人"（带感受词或自述习惯）→ preferences；"我是/我们…"→ profile。

## 已有规则
{existing_rules}

## 用户发言
{user_messages}

## 输出
- 有新指令：`{{"agent_rules": {{"content": "<合并后完整规则>"}}}}`
- 无新指令：`{{"agent_rules": {{}}}}`
""" + _COMMON_OUTPUT_RULES


