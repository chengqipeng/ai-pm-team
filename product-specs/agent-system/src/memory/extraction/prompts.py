"""四路并行提取提示词 — 精简版

设计原则（相对 v1）：
1. 共享「决策表」单一事实源，各路提示词只引用不重复论证
2. 所有示例使用通用占位符（<角色>/<实体>/<工具>/<值>），避免具名业务实体造成的过拟合
3. 识别规则采用"语义特征"而非"关键词枚举"（避免对特定动词/句式过拟合）
4. 混合句合并为一条通用原则
5. 输出规则统一共享
"""

# ═══════════════════════════════════════════════════════════
# 共享：跨维度决策表（四路提示词都引用这同一张表）
# ═══════════════════════════════════════════════════════════

_DECISION_TABLE = """
## 四维度决策表
| 维度        | 语义特征                                              | 识别信号                         |
|-------------|------------------------------------------------------|---------------------------------|
| profile     | 陈述【我 / 我们团队 / 我们公司】稳定的身份或长期背景       | 职位、履历、KPI、所属组织特征      |
| preferences | 陈述【我】自己的喜好、习惯、厌恶、标准（描述"我这个人"）    | 可含"我"，也可口语化行为暗示      |
| agent_rules | 规定【Agent 未来】的角色、输出、沟通、流程（命令"该怎么做"） | 具持久性（以后/每次/默认），非单次 |
| entities    | 陈述【第三方】（客户、联系人、对手）的事实或他们的要求      | 主语是具名或可指代的第三方         |
| 不提取       | 单次操作、纯查询、寒暄、当前会话的一次性偏好              | 含"帮我/这次/刚才"或无持久意义    |
"""

# ═══════════════════════════════════════════════════════════
# 共享：通用输出规则
# ═══════════════════════════════════════════════════════════

_COMMON_OUTPUT_RULES = """
## 输出规则
- abstract：一句话概述，≤50 字
- overview：Markdown 结构化（`##` + `-`），≤200 字
- content：完整叙述，Markdown 格式
- 所有文本使用 {output_language}；auto 则跟随对话主要语言
- 同一句含多个维度的信息，各维度独立判断各自提取
- 仅输出 JSON，无其他说明
- 无需提取时返回各路约定的空结构
"""

# ═══════════════════════════════════════════════════════════
# Profile — 用户画像
# ═══════════════════════════════════════════════════════════

PROFILE_EXTRACT_PROMPT = """从用户发言中提取【稳定、长期有效】的身份背景，合并到已有画像后输出完整版本。

## 属于 profile
用户对【我 / 我们团队 / 我们公司】的描述：
- 职位 / 角色 / 职级 / 履历 / 所在区域
- 所属团队或公司的特征（业务、规模、文化、工具、客户行业）
- 长期可量化指标（KPI、预算、管理规模、跟进客户数）
- 允许主语省略，凡语义上可判断为用户自述即可

## 不属于
见决策表其他维度：
- 我的喜好/习惯/厌恶 → preferences
- 对 Agent 的持久指令 → agent_rules
- 具体第三方的事实 → entities（"客户反馈我们…" 归 entities）
- 单次操作、纯数值孤岛 → 不提取

{decision_table}

## 已有画像
{existing_profile}

## 用户发言
{user_messages}

## 输出
- 有新增：`{{"profile": {{"content": "<合并后完整画像>"}}}}`
- 无新增：`{{"profile": {{}}}}`

{output_rules}
""".replace("{decision_table}", _DECISION_TABLE).replace("{output_rules}", _COMMON_OUTPUT_RULES)

# ═══════════════════════════════════════════════════════════
# Preferences — 用户偏好
# ═══════════════════════════════════════════════════════════

PREFERENCES_EXTRACT_PROMPT = """从用户发言中提取【用户自己的喜好/习惯/厌恶/个人标准】。

## 识别标准（满足任一即可）
- 第一人称直接表达：喜好/厌恶/习惯/要求/在意的维度
- 自述行为模式：频率（总是/每次/一般/从不）、条件（"如果…我就…"）、时间习惯
- 口语化暗示：感受词（受不了/头疼/看不下去）或反问（"能用图就别用表"）

## 不属于
- **命令 Agent**（无个人感受词的规则式 / 含"报告要.../ 以后.../回复要..."）→ agent_rules
- **身份或组织特征**（"我是X"、"我们团队都用<工具>"、"我们公司做<行业>"）→ profile
- **第三方偏好**（"<角色>喜欢<X>"、"<公司>要求<X>"）→ entities
- **单次操作**（"这次用<X>"、"帮我<X>"）→ 不提取

## 关键边界（见决策表）
| 句式                    | 归属          | 判定依据                  |
|-------------------------|---------------|--------------------------|
| "我要求金额用万"         | preferences   | "我要求"= 个人标准        |
| "金额统一用万"（无主语）  | agent_rules   | 规则式、持久性输出约束    |
| "我们部门不加班"         | profile       | 组织文化                  |
| "我一般不加班"           | preferences   | 个人习惯                  |

{decision_table}

## 粒度
- 每条对应一个独立维度（用 slug 区分：reply_format / data_display / work_habit / communication 等）
- 同一维度只保留一条（描述最新状态）

## 用户发言
{user_messages}

## 输出
```json
{{"preferences": [{{"slug": "<英文下划线>", "abstract": "<1 句>", "overview": "<Markdown>", "content": "<完整叙述>"}}]}}
```
无偏好返回 `{{"preferences": []}}`。

{output_rules}
""".replace("{decision_table}", _DECISION_TABLE).replace("{output_rules}", _COMMON_OUTPUT_RULES)

