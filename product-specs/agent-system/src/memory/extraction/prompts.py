"""四路并行提取提示词 v2

设计原则：
1. 语义原则驱动：用归属判定规则代替具体句式枚举，避免过拟合
2. 统一格式：四路提示词共享相同的章节结构（识别原则→排除规则→边界判定→输出格式）
3. 通用占位符：具名业务实体替换为 <实体>/<角色>/<工具>
4. 紧凑：每个提示词 ≤ 1500 chars
5. 真歧义容忍：省略主语等真歧义场景允许 LLM 按最直接证据判断

章节结构（四路统一）：
  ## 识别原则    — 正面定义：什么属于本路
  ## 排除规则    — 负面定义：什么不属于本路（语义规则，非句式枚举）
  ## 边界判定    — 最易混淆的归属判定规则（≤3 条）
  ## 输入/输出   — 占位符 + JSON 格式
"""

# ═══════════════════════════════════════════════════════════
# 共享：通用输出规则
# ═══════════════════════════════════════════════════════════

_COMMON_OUTPUT_RULES = """
## 输出规则
- abstract ≤50 字；overview 为 Markdown（`##`+`-`）≤200 字；content 完整叙述
- 文本使用 {output_language}（auto 则跟随对话主要语言）
- 多维度混合：同句含多维度时，各维度独立判断，各自提取属于自己的部分
- 只输出 JSON，不写其他说明
"""


# ═══════════════════════════════════════════════════════════
# Profile — 用户画像
# ═══════════════════════════════════════════════════════════

PROFILE_EXTRACT_PROMPT = """从用户发言中提取【稳定、长期有效】的身份背景，合并到已有画像后输出完整版本。

## 识别原则
用户对【我 / 我们团队 / 我们公司】的稳定属性描述：
- 职位 / 履历 / 所在区域 / 长期可量化指标（KPI、预算、团队或客户规模）
- 职场状态（新入职 / 在熟悉业务 / 调岗等当前身份阶段）
- 所属组织的业务、规模、文化、工具、覆盖行业
- 允许省略主语；从语义可判为用户自述即可

判别：**该信息在下一个新会话里对 Agent 理解"这个用户是谁"是否仍有帮助**。

## 排除规则
以下内容不属于本路，即使句中出现"我"字：
- 个人喜好、习惯、厌恶（态度动词：喜欢/讨厌/习惯/在意）→ preferences
- 对 Agent 行为的持久指令（动作指向 Agent 产物）→ agent_rules
- 第三方事实（核心主语是第三方，含"客户反馈我们…"）→ entities
- 单次操作、临时状态、孤立数值 → 不提取

## 边界判定
- profile vs preferences：集体属性（"我们部门/团队/公司"的文化、制度、工具）→ profile；个人态度（"我个人喜欢/习惯/在意"）→ preferences
- profile vs entities：主语是"我/我们"描述自身特征 → profile；主语是第三方或描述第三方事实 → entities
- 提取 vs 不提取：稳定身份信息（跨会话仍有效）→ 提取；临时状态（"今天心情不好"）→ 不提取

## 已有画像
{existing_profile}

## 用户发言
{user_messages}

## 输出格式
- 有新增：`{{"profile": {{"content": "<合并后完整画像>"}}}}`
- 无新增：`{{"profile": {{}}}}`
""" + _COMMON_OUTPUT_RULES


# ═══════════════════════════════════════════════════════════
# Preferences — 用户自己的喜好/习惯/标准
# ═══════════════════════════════════════════════════════════

PREFERENCES_EXTRACT_PROMPT = """从用户发言中提取【用户自己】的喜好、习惯、厌恶或个人标准。

## 识别原则
提取"描述用户本人是什么样的人"的可复用信息：
- 个人喜好与厌恶（喜欢/讨厌/受不了/偏好/倾向）
- 稳定的行为习惯（频率 / 条件 / 时间模式）
- 个人要求的品质标准（在意/要求/觉得应该）

判别：**该信息脱离当前上下文后，在下一个新会话里对理解"这个用户"是否仍有价值**。

## 排除规则
以下内容不属于本路，本路返空：
- 动作指向 Agent 产物的持久指令（主语是报告/回复/邮件/分析等 Agent 输出物，或省略主语但语义上约束 Agent 行为）→ agent_rules。判定标准：如果去掉这句话 Agent 的输出行为会改变，则属于 agent_rules 而非 preferences。
- 描述组织/团队的集体属性 → profile
- 描述第三方的偏好或事实 → entities
- 单次反馈或操作指令（"这次 X"、"帮我 X"）→ 不提取

## 边界判定
- preferences vs agent_rules：核心主语是"我"且表达个人态度（无行为约束意图）→ preferences；句子的效果是约束 Agent 未来输出行为（格式/语气/长度/内容/频率）→ agent_rules。当一句话同时含个人态度和 Agent 行为约束时，仅提取个人态度部分到 preferences，行为约束部分留给 agent_rules 路。
- preferences vs profile："我个人"的态度/习惯/风格 → preferences；"我们部门/团队/公司"的集体属性 → profile
- 提取 vs 不提取：可跨会话复用的稳定偏好 → 提取；单次场景的临时调整 → 不提取

## 粒度
- 按语义维度分条（reply_format、data_display、work_habit、communication 等 slug）
- 同一维度仅保留一条（最新状态）

## 用户发言
{user_messages}

## 输出格式
```json
{{"preferences": [{{"slug": "<英文下划线>", "abstract": "<1 句>", "overview": "<Markdown>", "content": "<完整叙述>"}}]}}
```
无偏好返回 `{{"preferences": []}}`。
""" + _COMMON_OUTPUT_RULES


# ═══════════════════════════════════════════════════════════
# Agent Rules — 对 Agent 未来行为的持久约束
# ═══════════════════════════════════════════════════════════

AGENT_RULES_EXTRACT_PROMPT = """从用户发言中提取【对 Agent 未来行为的持久约束】，合并到已有规则后输出完整版本。

## 识别原则
两个条件同时满足：
1. **行为指向 Agent**：约束 Agent 的输出、沟通、流程、角色或禁止事项。标志：主语或隐含主语是 Agent / 报告 / 回复 / 邮件 / 分析等 Agent 产物。
2. **持久性**：规则可复用到未来同类场景，不是"这次/刚才"的单次调整。

判别：**该规则在下一次类似请求中 Agent 是否应继续遵守**。

## 排除规则
以下内容不属于本路，本路返空：
- 句子整体描述用户本人的态度/习惯/性格（主语是"我"，谓语是态度动词）→ preferences
- 纯身份或组织描述 → profile
- 对第三方事实的纯陈述（动作未指向 Agent，而是描述第三方的要求/特点/状态）→ entities。判定标准：句子是在"告知 Agent 一个事实"还是"命令 Agent 做某事"？前者是 entities，后者是 agent_rules。
- 单次调整（"这次 X"）、评价（"感觉你像 X"）、感叹 → 不提取

## 边界判定
- agent_rules vs preferences：句中存在泛化的 Agent 行为约束（格式/长度/频率/渠道/流程）→ agent_rules；仅表达个人态度无 Agent 行为约束 → preferences。一句话同时含两者时各路独立提取。
- agent_rules vs entities：动作指向 Agent（"跟 <实体> 沟通要 X"）→ agent_rules；纯陈述第三方要求（"<实体> 那边要求 X"）→ entities
- 提取 vs 不提取：持久性（"以后/每次/所有"等泛化标志）→ 提取；单次性（"这次/刚才/算了"）→ 不提取

## 已有规则
{existing_rules}

## 用户发言
{user_messages}

## 输出格式
- 有新指令：`{{"agent_rules": {{"content": "<合并后完整规则>"}}}}`
- 无新指令：`{{"agent_rules": {{}}}}`
""" + _COMMON_OUTPUT_RULES


