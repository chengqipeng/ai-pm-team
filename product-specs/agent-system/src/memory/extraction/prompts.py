# Entities — 第三方客观事实
# ═══════════════════════════════════════════════════════════

ENTITIES_EXTRACT_PROMPT = """从对话中提取关于【第三方】的客观事实。第三方指非用户本人、非用户所在组织、非 Agent 的对象（客户、联系人、对手、对标企业等）。

## 识别原则
任何关于第三方的可复用事实：
- 角色关系 / 业务与规模 / 偏好与风格
- 第三方的要求或规则（陈述式，如"<实体> 那边要求 X"）
- 对用户方的反馈、评价、承诺
- 竞争情报、时效性信息
- 用户对第三方的判断（主语"我"但内容描述的是第三方）

第三方主体识别：具名公司/人名/品牌、可锁定的代词（这家公司/他们）、关系动词（跟进/对接/评估/合作）的宾语。

## 排除规则
以下内容不属于本路，本路返空：
- 用户自身的履历/团队/公司特征（无关系动词串联到第三方当前事实）→ profile
- 用户自己的偏好 → preferences
- 命令 Agent 行为的持久指令（动作指向 Agent）→ agent_rules
- 疑问句 / 纯查询 / 操作指令（"帮我发邮件给 X"）→ 不提取
- CRM 系统已有的结构化字段值（金额/阶段/电话/邮箱）→ 不提取，仅保留客户名和人名作为定位锚点

## 边界判定
- entities vs profile：主语是第三方或描述第三方事实 → entities；主语是"我/我们"描述自身特征 → profile。特殊情况：纯履历提到公司名但无关系动词 → profile；履历+关系动词串联到第三方当前事实 → entities
- entities vs agent_rules：纯陈述第三方的要求/特点 → entities；命令 Agent 针对该实体采取行动 → agent_rules
- 提取 vs 不提取：增量认知（系统中查不到的洞察）→ 提取；系统数据字段值（可通过工具实时查询）→ 不提取

## 已有实体
{existing_entities}

## 对话（仅用户发言）
{conversation}

## 输出格式
```json
{{"entities": [{{"abstract": "<1 句>", "overview": "<Markdown>", "content": "<完整叙述>", "merge_key": "<如 公司/项目>", "parent_entity": "<父实体>"}}]}}
```
无有效实体返回 `{{"entities": []}}`。
""" + _COMMON_OUTPUT_RULES
