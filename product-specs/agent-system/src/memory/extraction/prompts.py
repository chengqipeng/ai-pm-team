# Entities — 第三方客观事实
# ═══════════════════════════════════════════════════════════

ENTITIES_EXTRACT_PROMPT = """从对话中提取关于【第三方】的客观事实。第三方指非用户本人、非用户所在组织、非 Agent 的对象（客户、联系人、对手、对标企业等）。

## 第三方主体识别
- 具名：公司 / 人名 / 品牌
- 可指代：上下文能锁定到具体第三方的代词（这家公司 / 那个客户 / 他们 / 客户反馈）
- 顺带提及：只要句子里出现关系动词（跟进 / 对接 / 评估 / 服务 / 合作 / 谈 / 打交道），宾语里的公司或人名就是第三方实体

## 履历上下文不提取（关键）
当整句完全在描述【用户自己的履历、职责、所在组织特征】而无关系动词串联第三方时，不提取 entities。区分方法：
- 纯履历（不提 entities）：
  - "之前在 <A> 做过"、"我在 <行业> 干了十年"、"我负责 <行业> 客户"、"我老板是 <角色>"
- 履历+关系动词（**要提 entities**，即使前半句是自述）：
  - "我管理 10 人团队，主要**跟进** <A> 和 <B>" → 提 A、B
  - "我是技术出身，<A> 那边的技术评估我来**对接**" → 提 A
  - "我负责 <X>，核心客户是 <A> 和 <B>" → 提 A、B

## 属于 entities
关于第三方的任一事实：角色关系 / 业务与规模 / 偏好与风格 / 要求或规则（陈述式）/ 对用户方的反馈 / 竞争情报 / 时效性信息 / 用户对第三方的判断（主语"我"但内容是第三方）。

## 不提取的情况
- **疑问句 / 查询句**（"<A> 的 X 有几个？"、"<A> 的报价是多少？"）→ 整路空，属单次查询
- **操作指令的对象**（"帮我发邮件给 <X>"、"帮我约 <X> 的会"、"把邮件发给 <X>"）→ 整路空
  - 判别：即使句中提到第三方人名，只要整句是"帮我 / 请 + 对 <X> 的操作"，<X> 是操作对象而非事实陈述的主体
- 孤立数值、联系方式 → 整路空

## 核心边界（易混淆处）
| 句式                             | 归属          |
|----------------------------------|---------------|
| "<实体> 那边要求正式语气"（陈述）   | entities      |
| "跟 <实体> 沟通要用正式语气"（指令）| agent_rules   |
| "客户反馈我们响应快"               | entities（第三方反馈）|
| "我们响应快"                      | profile（自述）       |
| "帮我问 <角色> …"                 | 不提取（单次操作）    |

其他不属于：用户履历/团队/公司特征 → profile；用户自己的偏好 → preferences；孤立数值 → 不提取。

## 已有实体
{existing_entities}

## 对话（仅用户发言）
{conversation}

## 输出
```json
{{"entities": [{{"abstract": "<1 句>", "overview": "<Markdown>", "content": "<完整叙述>", "merge_key": "<如 公司/项目>", "parent_entity": "<父实体>"}}]}}
```
无有效实体返回 `{{"entities": []}}`。
""" + _COMMON_OUTPUT_RULES
