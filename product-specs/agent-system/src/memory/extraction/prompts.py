# Agent Rules — Agent 行为准则
# ═══════════════════════════════════════════════════════════

AGENT_RULES_EXTRACT_PROMPT = """从用户发言中提取对【Agent 未来行为】的持久约束，合并到已有规则后输出完整版本。

## 识别条件（两个必须同时满足）
1. 指向 Agent 的未来行为：角色定义 / 输出格式 / 沟通风格 / 流程约束 / 禁止事项
2. 具备持久性：
   - 显式标志（以后/每次/默认/统一/所有），或
   - 语义上明显是规则（输出/沟通/流程的泛化要求），非"这次/刚才"

允许主语省略——"报告要含<X>"、"回复不超过<N>字" 等规则式指令即使无"你"字也属 agent_rules。

## 不属于
- **描述"我这个人"**（含感受词/口语化/条件性个人行为/时间习惯）→ preferences
- **身份或组织**（"我是<角色>"、"我们<组织>的<特征>"）→ profile
- **第三方陈述**（"<公司>那边要求<X>" 是事实陈述）→ entities
- **单次操作**（"这次/刚才/帮我..."，无持久标志）→ 不提取
- **评价/感叹**（"感觉你像<X>"等，无明确约束）→ 不提取

## 关键边界（见决策表）
| 句式                              | 归属          |
|-----------------------------------|---------------|
| "以后分析要深入一些"                | agent_rules   |
| "这次分析深入一些"                  | 不提取        |
| "跟<公司>沟通要用正式语气"           | agent_rules（命令 Agent）|
| "<公司>那边要求用正式语气"           | entities（陈述事实）     |
| "你就像我的私人助理一样"             | agent_rules（定义角色）  |
| "感觉你就像私人助理"                | 不提取（评价）           |

## 混合句
一句含多种意图时，各维度独立提取自己那部分。例如「我喜欢数据驱动，报告要有数据支撑」→ preferences 取前半句，agent_rules 取后半句。

{decision_table}

## 已有规则
{existing_rules}

## 用户发言
{user_messages}

## 输出
- 有新指令：`{{"agent_rules": {{"content": "<合并后完整规则>"}}}}`
- 无新指令：`{{"agent_rules": {{}}}}`

{output_rules}
""".replace("{decision_table}", _DECISION_TABLE).replace("{output_rules}", _COMMON_OUTPUT_RULES)

