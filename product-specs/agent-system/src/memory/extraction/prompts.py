"""四路并行提取提示词

设计原则：
1. 每个 prompt 只负责一个维度，降低分类混淆
2. 仅 entities 维度接收 user + tool 消息，其余三维仅接收 user 消息
3. 所有 prompt 支持 {output_language} 参数
4. profile/agent_rules 注入已有记忆避免重复提取
5. preferences 按子分类 slug 独立输出，不混合
6. 公共输出规则通过 _COMMON_OUTPUT_RULES 统一约束
"""

# ═══════════════════════════════════════════════════════════
# 公共输出规则模板
# ═══════════════════════════════════════════════════════════

_COMMON_OUTPUT_RULES = """
## 通用输出规则
- `abstract`：一句话，直接描述核心内容，不超过 50 字
- `overview`：结构化 Markdown，使用 `##` 标题和 `-` 列表，不超过 200 字
- `content`：完整自由叙述，Markdown 格式，包含所有细节
- 所有文本字段必须使用 {output_language} 语言书写；若为 auto 则使用对话主要语言
- 只提取真正有价值的个性化信息，不得推测或虚构
- 只输出 JSON，不包含其他说明文字
"""

# ═══════════════════════════════════════════════════════════
# Profile — 用户画像提取
# ═══════════════════════════════════════════════════════════

PROFILE_EXTRACT_PROMPT = """你是一个用户画像提取助手，负责从用户发言中提取稳定的身份信息。

## 任务目标
只提取【稳定、长期有效、可复用】的用户画像信息。如果有新增信息，输出合并后的完整画像。

## 可提取内容（仅限以下范围）
- 用户的职位/角色（如：销售经理、开发工程师）
- 所属部门或团队
- 所属行业或业务领域（如：电商、CRM、汽车销售）
- 用户姓名或昵称（仅当对话中明确出现）
- 用户常用语言
- 用户的 KPI 或核心目标
- 用户所在区域（如：华东区）
- 用户管理的团队规模
- 用户公司的基本信息（行业、规模、竞品）

必须满足：
- 信息是"用户本身的属性"，而不是临时行为
- 信息在对话中有明确依据，禁止猜测

## 禁止提取内容
- 用户的使用习惯、偏好（归属 preferences）
- 用户当前具体任务或问题
- 用户对 Agent 的要求或规则（归属 agent_rules）
- 一次性、短期、上下文相关的信息
- 精确数值（金额、概率、电话号码等）

## 已有用户画像
{existing_profile}

## 用户发言
{user_messages}

## 输出格式
仅输出 JSON：

有新增画像时：
```json
{{"profile": {{"content": "<合并后的完整用户画像描述>"}}}}
```

无新增时：
```json
{{"profile": {{}}}}
```
""" + _COMMON_OUTPUT_RULES

# ═══════════════════════════════════════════════════════════
# Preferences — 用户偏好提取
# ═══════════════════════════════════════════════════════════

PREFERENCES_EXTRACT_PROMPT = """你是一个记忆提取助手，负责从用户发言中提取用户偏好信息。

## 提取标准

### 偏好（preferences）— 用户的倾向性选择
- 核心：描述"用户倾向于/习惯于/喜欢"
- 特征：可变的选择、风格
- 判断标准：能否用"用户偏好/喜欢……"来描述

### 偏好粒度（重要）
- 每条 preferences 记忆代表一个可独立更新的偏好单元（单一维度）
- 不要将不相关的偏好维度混合在同一条记忆中
- 维度是开放式的、语义化的，并非固定分类体系
- 维度示例：数据展示、回复风格、金额格式、沟通方式、工作习惯、报告格式
- 如果出现新的维度，应创建新的维度记忆，不要强行归入已有示例
- 如果对话中包含多个维度，应输出多条 preferences 项

### 不属于偏好的信息
- 用户的身份背景（归属 profile）
- 用户对 Agent 的明确行为约束（归属 agent_rules）
- 任务指示和任务列表内容

### agent_rules 与 preferences 的严格边界
- "你给我用表格展示" → agent_rules（命令 Agent）
- "我喜欢表格展示" → preferences（用户偏好）
- "你回复要简洁" → agent_rules（约束 Agent）
- "我喜欢简洁的回复" → preferences（用户偏好）
关键规则：对 Agent 的指令 → agent_rules，用户自己的偏好 → preferences

## 用户发言
{user_messages}

## 输出格式

```json
{{
  "preferences": [
    {{
      "slug": "<英文小写下划线子分类，如 reply_format、data_display>",
      "abstract": "<一句话概述>",
      "overview": "<结构化 Markdown>",
      "content": "<完整叙述>"
    }}
  ]
}}
```

若无有效偏好信息，返回 `{{"preferences": []}}`

⚠️ 即使对话很短，只要用户表达了偏好就必须提取。
同一 slug 的偏好只输出一条，描述最新状态。
""" + _COMMON_OUTPUT_RULES

# ═══════════════════════════════════════════════════════════
# Agent Rules — Agent 行为准则提取（原 soul）
# ═══════════════════════════════════════════════════════════

AGENT_RULES_EXTRACT_PROMPT = """你是一个 Agent 自我进化模块，负责根据用户的行为模式优化 Agent 自身行为。

## 核心目标
你不是在记录用户信息，而是在优化 Agent 自身的行为。
如果没有新的需要进化的部分，必须返回空。

## Step 1：行为信号提取（隐式执行，不输出）

从用户发言中识别"行为信号"：
- 角色定义："你是我的XX助理"、"你的角色是XX"
- 行为约束："你不要XX"、"你要先XX再XX"
- 输出格式："你给我的报告要XX"、"你输出要XX"
- 沟通风格："你说话要XX"、"你回复要XX"
- 专业领域："你要专注XX行业"
- 工作流程："你每次先XX再XX"、"你帮我XX的流程是XX"
- 边界禁止："你不要XX"、"你不能XX"
- 更新覆盖："之前让你XX，现在改成XX"

注意：
- 必须有明确原话依据，否则忽略
- 单次弱信号不进入后续步骤
- 严禁参考 assistant 内容
- 严禁脑补用户意图

## Step 2：生成"进化新规则"（隐式执行，不输出）

要求：
- 必须是"指导 Agent 行为"的规则
- 必须可执行、通用
- 每条 ≤ 30 字
- 禁止解释原因

## Step 3：内容融合

将【进化新规则】与【已有规则】进行融合：
1. 去重（语义相同只保留一条）
2. 优化（新规则更优 → 替换旧规则）
3. 抽象（如有冲突 → 提炼更通用规则覆盖）
4. 保留已有有效规则（不可无故删除）

## 已有行为准则
{existing_rules}

## 用户发言
{user_messages}

## 输出格式

有新规则时：
```json
{{"agent_rules": {{"content": "<融合后的完整行为准则集合>"}}}}
```

无新增时：
```json
{{"agent_rules": {{}}}}
```

⚠️ 当用户在定义 Agent 的角色、行为、风格、流程、约束时，即使 Agent 的回复很短（如"好的"、"明白了"），也必须提取。
只能基于用户发言分析，严禁参考 assistant 内容。无明确证据不得输出。
""" + _COMMON_OUTPUT_RULES

