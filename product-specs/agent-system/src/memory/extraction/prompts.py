# Entities — 第三方客观事实
# ═══════════════════════════════════════════════════════════

ENTITIES_EXTRACT_PROMPT = """从对话中提取关于【第三方】的客观事实。第三方指非用户本人、非用户所在组织、非 Agent 的对象（客户、联系人、对手、对标企业等）。

## 识别原则
任何关于第三方的可复用事实：
- 角色关系 / 业务与规模 / 偏好与风格
- 第三方的要求或规则（陈述式，如"<实体> 那边要求 X"）
- 对用户方的反馈、评价、承诺
- 竞争情报、时效性信息
- 用户对第三方的判断（主语"我"但内容描述的是第三方）

## 第三方主体识别
- 具名：公司 / 人名 / 品牌
- 可指代：上下文能锁定的代词（这家公司 / 那个客户 / 他们 / 客户反馈）
- 顺带提及：句中出现关系动词（跟进 / 对接 / 评估 / 服务 / 合作 / 谈 / 打交道等）时，宾语里的公司或人名即第三方

## 履历上下文不提取
当整句描述的是【用户自己的履历、职责或所在组织的特征】且未用关系动词串联到第三方的当前事实时，即使提到公司名也不提取为 entities。
- 纯履历（不提）："之前在 <A> 做过"、"负责 <行业> 客户"、"我老板是 <角色>"
- 履历+关系动词（提 entities）："我管理 10 人团队，主要**跟进** <A>"、"<A> 那边的技术评估我来**对接**"

## 不属于
- 用户履历、团队或公司特征 → profile
- 用户自己的偏好 → preferences
- 命令 Agent 的持久指令（"跟 <实体> 沟通要 X"）→ agent_rules
- 疑问句 / 纯查询（"<A> 的 X 有几个？"）→ 不提取
- 操作指令的对象（"帮我发邮件给 <X>"、"帮我约 <X> 的会"）→ 不提取
- 孤立数值、联系方式 → 不提取

## 核心边界
| 句式                             | 归属          |
|----------------------------------|---------------|
| "<实体> 那边要求正式语气"（陈述）   | entities      |
| "跟 <实体> 沟通要用正式语气"（指令）| agent_rules   |
| "客户反馈我们响应快"               | entities（第三方反馈） |
| "我们响应快"                      | profile（自述）        |
| "帮我问 <角色> …"                 | 不提取（单次操作）     |

## 已有实体
{existing_entities}

## 对话（仅用户发言）
{conversation}

## 输出
```json
{{"entities": [{{"abstract": "<1 句>", "overview": "<Markdown>", "content": "<完整叙述>", "merge_key": "<如 公司/项目>", "parent_entity": "<父实体>"}}]}}
```
无有效实体返回 `{{"entities": []}}`。
""" + _COMMON_OUTPUT_RULES
