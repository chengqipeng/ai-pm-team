# Entities — 第三方事实
# ═══════════════════════════════════════════════════════════

ENTITIES_EXTRACT_PROMPT = """从对话中提取关于【第三方】（非用户、非用户所在组织、非 Agent）的客观事实。

## 第三方主体
- 具名：客户公司 / 联系人 / 竞争对手 / 行业对标
- 指代（上下文可锁定到具体第三方即可）：
  - 「这家公司 / 那个客户 / 他 / 他们 / 客户反馈」
- 允许：用户自述中顺带提到的第三方（如"主要跟进<X>和<Y>" → 第三方实体）

## 属于 entities
关于第三方的任一事实：
- 角色与组织：谁决策、谁汇报、业务、规模、内部流程
- 偏好/风格/习惯
- 要求或规则（"<公司>要求<X>" — 陈述事实）
- 对用户方的反馈/评价
- 竞争情报、时效性信息
- 用户对第三方的判断（主语"我"但内容描述的是第三方）

## 不属于
- 用户自己或自己组织的描述 → profile
  - 即使顺带提到曾经工作过的公司或客户行业，只要句子核心是用户履历/职责 → profile
- 用户自己的偏好 → preferences
- 命令 Agent 的持久指令（"跟<公司>沟通要用正式语气"）→ agent_rules
- 单次操作（"帮我问<角色>..."）→ 不提取
- 孤立数值/金额/联系方式 → 不提取

## 关键边界
| 句式                                     | 归属        |
|------------------------------------------|-------------|
| "<公司>那边要求用正式语气"（陈述事实）       | entities    |
| "跟<公司>沟通要用正式语气"（指令 Agent）     | agent_rules |
| "客户反馈我们响应快"                       | entities    |
| "我们响应快"                              | profile     |

{decision_table}

## 已有实体
{existing_entities}

## 对话（仅用户发言）
{conversation}

## 输出
```json
{{"entities": [{{"abstract": "<1 句>", "overview": "<Markdown>", "content": "<完整叙述>", "merge_key": "<如 公司X/项目Y>", "parent_entity": "<父实体>"}}]}}
```
无有效实体返回 `{{"entities": []}}`。

{output_rules}
""".replace("{decision_table}", _DECISION_TABLE).replace("{output_rules}", _COMMON_OUTPUT_RULES)
