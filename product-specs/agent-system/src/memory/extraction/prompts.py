# Profile — 用户画像
# ═══════════════════════════════════════════════════════════

PROFILE_EXTRACT_PROMPT = """从用户发言中提取【稳定、长期有效】的身份背景，合并到已有画像后输出完整版本。

## 识别原则
用户对【我 / 我们团队 / 我们公司】的稳定属性描述：
- 职位 / 履历 / 所在区域 / 长期可量化指标（KPI、预算、团队或客户规模）
- 职场状态（新入职 / 在熟悉业务 / 调岗等当前身份阶段）
- 所属组织的业务、规模、文化、工具、覆盖行业
- 允许省略主语；从语义可判为用户自述即可

判别：**该信息在下一个新会话里对 Agent 理解"这个用户是谁"是否仍有帮助**。

## 主语归属检查（关键）
只有当句子的**核心主语**是"我 / 我们"或从语境清晰指向用户自己时才属本路。以下主语不属本路：
- 主语是第三方（具名公司、人名、"他们"、"这家公司"）→ 该句归 entities 的事，本路返空
- 主语是 Agent 产物（报告、回复、输出、邮件）→ 该句归 agent_rules 的事，本路返空
- 主语是一般第三人称情境（"大客户…小客户…"描述业务处理方式而非自己的身份）→ 归 preferences 的事，本路返空

## 不属于
- 我的喜好/习惯/厌恶 → preferences
- 对 Agent 的持久指令 → agent_rules
- 第三方事实（含"客户反馈我们…" 主语是客户）→ entities
- 单次操作、孤立数值 → 不提取

## 已有画像
{existing_profile}

## 用户发言
{user_messages}

## 输出
- 有新增：`{{"profile": {{"content": "<合并后完整画像>"}}}}`
- 无新增：`{{"profile": {{}}}}`
""" + _COMMON_OUTPUT_RULES


# ═══════════════════════════════════════════════════════════
# Preferences — 用户自己的喜好/习惯/标准
# ═══════════════════════════════════════════════════════════

PREFERENCES_EXTRACT_PROMPT = """从用户发言中提取【用户自己】的喜好、习惯、厌恶或个人标准。

## 识别原则
提取"描述用户本人是什么样的人"的可复用信息：
- 个人喜好与厌恶
- 稳定的行为习惯（频率 / 条件 / 时间模式）
- 个人要求的品质标准

判别：**该信息脱离当前上下文后，在下一个新会话里对理解"这个用户"是否仍有价值**。

## 不属于（整句即归他路，本路返空）
- 纯指向 Agent 行为的规则式指令 → agent_rules 的事
  - 标志：主句主语或隐含主语是 Agent / 报告 / 回复 / 邮件等 Agent 产物，且无个人态度表达
  - 例：「分析报告要包含 X」、「跟 <实体> 沟通要 Y」、「不要自动发邮件」、「每次列出 X」、「以后要深入一些」
- 描述身份或组织 → profile
- 描述第三方偏好/事实 → entities
- 单次反馈/操作（"这次 X"、"帮我 X"）→ 不提取

## 多维度混合处理
一句话同时含个人态度与 Agent 规则时，两路独立判断各自提取：
- "我喜欢简洁，你回复不超过 3 句" → 本路取"偏好简洁"

## 真歧义处理
省略主语的条件句（如"如果急的微信说，不急的发邮件"）可能有多种合理解读。按文本最直接的证据判断；证据不足时可单侧提取。

## 核心边界
| 句式                        | 归属          |
|----------------------------|---------------|
| "我一般不加班"                | preferences（个人习惯）|
| "我们部门不加班"              | profile（组织文化）    |
| "<角色>喜欢 X"（第三方主语）    | entities（第三方偏好） |
| "报告要 X"（主语是 Agent 产物）| agent_rules 的事（本路空）|

## 粒度
- 按语义维度分条（reply_format、data_display、work_habit、communication 等 slug）
- 同一维度仅保留一条（最新状态）

## 用户发言
{user_messages}

## 输出
```json
{{"preferences": [{{"slug": "<英文下划线>", "abstract": "<1 句>", "overview": "<Markdown>", "content": "<完整叙述>"}}]}}
```
无偏好返回 `{{"preferences": []}}`。
""" + _COMMON_OUTPUT_RULES


