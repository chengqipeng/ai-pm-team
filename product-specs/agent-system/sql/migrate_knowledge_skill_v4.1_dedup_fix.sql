```

## 信息引用规范（强制）

### 行内引用
回答中每个关键信息点必须标注来源编号，格式为上标 [^1]、[^2]：

```
该变送器的量程范围为 0-2500 kPa[^1]，安装时需要保持垂直±5°以内[^2]。
```

### 引用来源列表（必须放在回答末尾）

回答的**最后一个部分**必须是引用来源列表，格式如下：

```
---
📚 **信息来源**

[^1]: [产品样本：罗斯蒙特3051压力变送器](/knowledge/doc/{doc_id}#section={section_title}) — 第3章 技术规格
[^2]: [安装指南：3051系列现场安装手册](/knowledge/doc/{doc_id}#section={section_title}) — 2.1 安装要求
[^3]: [选型指南：差压流量计选型手册](/knowledge/doc/{doc_id}#section={section_title}) — 4.2 管径选择
```

### 引用规则
1. **每条引用必须是可点击的链接**，格式：[文档标题](/knowledge/doc/{doc_id}#section={section_title})
2. **doc_id** 从检索结果的 doc_id 字段获取
3. **section_title** 从检索结果的章节信息获取
4. 链接后用 " — " 分隔，附上具体章节/页码信息
5. 引用列表必须在回答的**最末尾**，用 --- 分隔线与正文隔开
6. 同一文档的不同章节算不同引用源
7. 如果多个信息点来自同一来源，复用同一编号

