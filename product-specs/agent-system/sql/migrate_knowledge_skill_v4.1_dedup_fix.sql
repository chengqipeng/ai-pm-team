## 执行步骤

1. **意图分析**：判断用户查询属于以下哪种语义类型：
   - **对比型**：包含"对比"、"区别"、"哪个好"、"vs"、"优缺点"、"选型"等关键词，或涉及多个产品/方案
   - **参数查询型**：包含"参数"、"规格"、"量程"、"精度"、"尺寸"等技术指标词
   - **概述型**：包含"介绍"、"是什么"、"概述"、"了解"等泛化词
   - **操作指引型**：包含"怎么"、"如何"、"步骤"、"安装"、"配置"等动作词
   - **问题诊断型**：包含"故障"、"报错"、"不工作"、"异常"等问题描述词

2. **检索执行**：
   - 对比型：分别检索各对比对象（每个 top_k=3），如 knowledge_search(query="A 特点参数") + knowledge_search(query="B 特点参数")
   - 其他类型：knowledge_search(query="{query}", top_k=5)
   - 结果不足时（少于 2 条且相关度低于 0.4）可换一种表述重试，**最多重试 1 次**

   ### ⚠️ 去重规则（强制）
   - 多次检索返回相同 doc_id + section 的内容时，**只保留第一次出现的版本**，后续重复直接丢弃
   - 如果重试检索返回的结果与首次完全相同（相同的 doc_id 列表），**不要重复使用这些结果**
   - 宁可结果少一些，也**绝不重复输出相同内容**

3. **去重合并**（输出前必做）：
   - 将所有检索结果按 doc_id + section_title 分组
   - 同一文档同一章节的多个切片，合并为一条信息
   - 不同文档或不同章节的内容，分别呈现

4. **深度输出**：根据语义类型选择最佳输出形式（见下方规则）

## 输出形式选择规则

### 规则 1：对比型 → 输出对比表格

当用户语义涉及**多个产品/方案/选项的比较**时，必须输出结构化对比表格：

```
[自然语言总结一句核心结论]

| 对比维度 | 产品A | 产品B | ... |
|----------|-------|-------|-----|
| 适用场景 | ...   | ...   | ... |
| 核心参数 | ...   | ...   | ... |
| 优势     | ...   | ...   | ... |
| 局限     | ...   | ...   | ... |
| 推荐场景 | ...   | ...   | ... |

**选型建议**：[基于对比结果给出明确推荐]
```

触发条件：
- 用户提到 2 个及以上产品/型号/方案名称
- 使用了"对比"、"区别"、"哪个好"、"vs"、"选哪个"、"优缺点"等词
- 问"有哪些产品适合 XX 场景"（隐含多产品对比）

### 规则 2：参数查询型 → 输出参数列表/表格

当用户查询**单个产品的技术参数**时：

```
[产品名称] 核心技术参数：

| 参数项 | 规格值 | 备注 |
|--------|--------|------|
| ...    | ...    | ...  |

[补充说明（如有特殊工况条件）]
```

### 规则 3：概述型 → 输出独立产品概述

当用户想**了解某个产品/方案的整体情况**时，按结构化段落输出：

```
