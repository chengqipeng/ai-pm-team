# 评测执行
# ═══════════════════════════════════════════════════════════

def evaluate(archive: MemoryArchive, cases: list[TestCase]) -> dict:
    """执行评测并输出结果"""
    categories: dict[str, list[tuple[str, bool, float, float]]] = {}

    for case in cases:
        results = archive.search(case.query, top_k=5)
        hit_ids = [e.turn_id for e in results]

        if not case.expected_turn_ids:
            # 负例: 不应该命中任何内容
            precision = 1.0 if not hit_ids else 0.0
            recall = 1.0
            passed = len(hit_ids) == 0
        else:
            # 正例: 至少命中一个期望轮次
            hits = set(hit_ids) & set(case.expected_turn_ids)
            recall = len(hits) / len(case.expected_turn_ids) if case.expected_turn_ids else 0
            precision = len(hits) / len(hit_ids) if hit_ids else 0
            passed = len(hits) > 0  # 至少命中一个

        categories.setdefault(case.category, []).append((case.id, passed, recall, precision))

    return categories


def main():
    archive = build_archive()
    cases = build_test_cases()

    print(f"{'═' * 70}")
    print(f"  recall_context 召回率评测 — {len(cases)} 场景")
    print(f"  存档: {len(archive.entries)} 轮 | 检索模式: BM25(0.4) + Jaccard(0.6)")
    print(f"{'═' * 70}")
    print()

    results = evaluate(archive, cases)

    total_passed = 0
    total_cases = 0
    total_recall = 0.0

    for category, items in results.items():
        passed = sum(1 for _, p, _, _ in items if p)
        avg_recall = sum(r for _, _, r, _ in items) / len(items)
        avg_precision = sum(p for _, _, _, p in items) / len(items)
        total_passed += passed
        total_cases += len(items)
        total_recall += avg_recall * len(items)

        status = "✅" if passed / len(items) >= 0.80 else "❌"
        print(f"  {status} {category:8s} | {passed:3d}/{len(items)} ({passed/len(items)*100:5.1f}%) | "
              f"Recall {avg_recall*100:.1f}% | Precision {avg_precision*100:.1f}%")

        # 输出失败用例
        failed = [(id_, r, p) for id_, ok, r, p in items if not ok]
        if failed and len(failed) <= 5:
            for id_, r, p in failed:
                print(f"       ❌ {id_}: R={r*100:.0f}% P={p*100:.0f}%")
        elif failed:
            for id_, r, p in failed[:3]:
                print(f"       ❌ {id_}: R={r*100:.0f}% P={p*100:.0f}%")
            print(f"       ... 还有 {len(failed)-3} 个失败")
        print()

    overall_recall = total_recall / total_cases if total_cases > 0 else 0
    print(f"{'─' * 70}")
    print(f"  总计: {total_passed}/{total_cases} 通过 ({total_passed/total_cases*100:.1f}%)")
    print(f"  平均召回率: {overall_recall*100:.1f}%")
    print(f"{'═' * 70}")

    # 返回是否达标
    return total_passed / total_cases >= 0.80


if __name__ == "__main__":
    success = main()
    sys.exit(0 if success else 1)
