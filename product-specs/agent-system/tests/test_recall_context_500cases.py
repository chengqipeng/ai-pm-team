def _tokenize(text: str) -> list[str]:
    """简单分词（中英文混合）"""
    # 中文: 2-4字词；英文: 按空格/标点分
    cn = re.findall(r'[\u4e00-\u9fa5]{2,4}', text)
    en = [w.lower() for w in re.findall(r'[a-zA-Z0-9$¥%]+', text) if len(w) > 1]
    return cn + en


def _bm25_score(query_tokens: list[str], doc_tokens: list[str], k1=1.5, b=0.75, avg_dl=50) -> float:
    """BM25 单文档评分"""
    dl = len(doc_tokens)
    score = 0.0
    doc_tf = {}
    for t in doc_tokens:
        doc_tf[t] = doc_tf.get(t, 0) + 1
    for qt in query_tokens:
        if qt in doc_tf:
            tf = doc_tf[qt]
            numerator = tf * (k1 + 1)
            denominator = tf + k1 * (1 - b + b * dl / max(avg_dl, 1))
            score += numerator / denominator
    return score


def _jaccard_similarity(set_a: set, set_b: set) -> float:
    """Jaccard 相似度（模拟 Dense 语义匹配）"""
    if not set_a or not set_b:
        return 0.0
    intersection = len(set_a & set_b)
    union = len(set_a | set_b)
    return intersection / union if union > 0 else 0.0


class MemoryArchive:
    """内存模拟的 ContextArchive（BM25 + Jaccard 双路检索）"""

    def __init__(self):
        self.entries: list[ArchivedTurn] = []

    def add(self, turn_id: int, user_query: str, answer_preview: str,
            entities: list[str], tool_names: list[str],
            original_json: str = "", key_data: dict = None):
        self.entries.append(ArchivedTurn(
            turn_id=turn_id,
            timestamp=time.time() + turn_id,
            data_timestamp=time.time() + turn_id,
            user_query=user_query,
            answer_preview=answer_preview,
            entities=entities,
            keywords=[],
            tool_names=tool_names,
            skill_names=[],
            message_count=4,
            thread_id="test_thread",
            message_range=(0, 4),
            original_messages_json=original_json or json.dumps({"turn": turn_id}),
            tool_summaries=[],
            key_data=key_data or {},
        ))

    def search(self, query: str, top_k: int = 3) -> list[ArchivedTurn]:
        """模拟 hybrid_search: BM25(0.4) + Jaccard语义(0.6)"""
        query_tokens = _tokenize(query)
        query_token_set = set(query_tokens)

        scored = []
        for entry in self.entries:
            # BM25 源: user_query + answer_preview (对应 abstract 字段)
            bm25_text = f"{entry.user_query} {entry.answer_preview}"
            bm25_tokens = _tokenize(bm25_text)
            bm25 = _bm25_score(query_tokens, bm25_tokens)

            # Jaccard 源: user_query + answer_preview + entities + tool_names (对应 embed_text)
            embed_text = f"{entry.user_query} {entry.answer_preview} {' '.join(entry.entities)} {' '.join(entry.tool_names)}"
            embed_tokens = set(_tokenize(embed_text))
            jaccard = _jaccard_similarity(query_token_set, embed_tokens)

            # hybrid: dense 0.6 + sparse 0.4
            score = jaccard * 0.6 + (bm25 / max(bm25 + 1, 1)) * 0.4
            scored.append((score, entry))

        scored.sort(key=lambda x: -x[0])
        # Score 阈值 0.05 (Jaccard 比 cosine 低很多，阈值相应降低)
        return [e for s, e in scored[:top_k] if s > 0.05]


